class NamespaceServiceReproducedTests {

    @Test
    void deleteNamespaceReproducedTest() {
        Namespace v = new Namespace();
        v.setAppId("testApp");
        v.setNamespaceName("application");
        v.setId(1L);
        v.setDataChangeCreatedBy("apollo");
        v.setDataChangeLastModifiedBy("apollo");
        v.setClusterName("default");
        Namespace v1 = new Namespace();
        v1.setAppId("testApp");
        v1.setNamespaceName("application");
        v1.setId(9L);
        v1.setDataChangeCreatedBy("apollo");
        v1.setDataChangeLastModifiedBy("apollo");
        v1.setClusterName("child-cluster");
        Cluster v2 = new Cluster();
        v2.setName("default");
        v2.setId(1L);
        v2.setDataChangeCreatedBy("default");
        v2.setDataChangeLastModifiedBy("default");
        v2.setAppId("testApp");
        Cluster v3 = new Cluster();
        v3.setName("child-cluster");
        v3.setParentClusterId(1L);
        v3.setId(5L);
        v3.setDataChangeCreatedBy("default");
        v3.setDataChangeLastModifiedBy("default");
        v3.setAppId("testApp");
        ReleaseHistoryService mocked = Mockito.mock(ReleaseHistoryService.class);
        Mockito.when(mocked.batchDelete(Mockito.<String>any(), Mockito.<String>any(), Mockito.<String>any(), Mockito.<String>any())).thenReturn(1);
        NamespaceRepository mocked1 = Mockito.mock(NamespaceRepository.class);
        Mockito.when(mocked1.findByAppIdAndNamespaceNameOrderByIdAsc(Mockito.<String>any(), Mockito.<String>any())).thenReturn((List<Namespace>) (Object) new ArrayList<Object>((Collection<Object>) (Object) List.of(v, v1)));
        Mockito.when(mocked1.save(Mockito.<Object>any())).thenReturn(v);
        AuditService v4 = Mockito.mock(AuditService.class);
        AppNamespaceService v5 = Mockito.mock(AppNamespaceService.class);
        MessageSender v6 = Mockito.mock(MessageSender.class);
        ItemService mocked2 = Mockito.mock(ItemService.class);
        Mockito.when(mocked2.batchDelete(Mockito.anyLong(), Mockito.<String>any())).thenReturn(1);
        CommitService mocked3 = Mockito.mock(CommitService.class);
        Mockito.when(mocked3.batchDelete(Mockito.<String>any(), Mockito.<String>any(), Mockito.<String>any(), Mockito.<String>any())).thenReturn(1);
        ReleaseService mocked4 = Mockito.mock(ReleaseService.class);
        Mockito.when(mocked4.batchDelete(Mockito.<String>any(), Mockito.<String>any(), Mockito.<String>any(), Mockito.<String>any())).thenReturn(0);
        ClusterService mocked5 = Mockito.mock(ClusterService.class);
        Mockito.when(mocked5.findOne(Mockito.<String>any(), Mockito.<String>any())).thenReturn(v2);
        Mockito.when(mocked5.findChildClusters(Mockito.<String>any(), Mockito.<String>any())).thenReturn((List<Cluster>) (Object) new ArrayList<Object>((Collection<Object>) (Object) List.of(v3)));
        NamespaceBranchService v7 = Mockito.mock(NamespaceBranchService.class);
        NamespaceLockService v8 = Mockito.mock(NamespaceLockService.class);
        InstanceService mocked6 = Mockito.mock(InstanceService.class);
        Mockito.when(mocked6.batchDeleteInstanceConfig(Mockito.<String>any(), Mockito.<String>any(), Mockito.<String>any())).thenReturn(1);
        BizConfig v9 = Mockito.mock(BizConfig.class);
        NamespaceService v10 = new NamespaceService(mocked, mocked1, v4, v5, v6, mocked2, mocked3, mocked4, mocked5, v7, v8, mocked6, v9);
        ReflectionTestUtils.setField(v10, "namespaceRepository", mocked1);
        ReflectionTestUtils.setField(v10, "auditService", v4);
        ReflectionTestUtils.setField(v10, "appNamespaceService", v5);
        ReflectionTestUtils.setField(v10, "itemService", mocked2);
        ReflectionTestUtils.setField(v10, "commitService", mocked3);
        ReflectionTestUtils.setField(v10, "releaseService", mocked4);
        ReflectionTestUtils.setField(v10, "clusterService", mocked5);
        ReflectionTestUtils.setField(v10, "namespaceBranchService", v7);
        ReflectionTestUtils.setField(v10, "releaseHistoryService", mocked);
        ReflectionTestUtils.setField(v10, "namespaceLockService", v8);
        ReflectionTestUtils.setField(v10, "instanceService", mocked6);
        ReflectionTestUtils.setField(v10, "messageSender", v6);
        ReflectionTestUtils.setField(v10, "bizConfig", v9);
        Namespace v11 = new Namespace();
        v11.setAppId("testApp");
        v11.setNamespaceName("application");
        v11.setId(1L);
        v11.setClusterName("default");
        Namespace v12 = v10.deleteNamespace(v11, "apollo");
        Assertions.assertNotNull(v12);
        Assertions.assertEquals("testApp", v12.getAppId());
        Assertions.assertEquals("application", v12.getNamespaceName());
        Assertions.assertEquals(1791727286461L, v12.getDeletedAt());
        Assertions.assertEquals("apollo", v12.getDataChangeLastModifiedBy());
        Assertions.assertEquals("default", v12.getClusterName());
        Assertions.assertTrue(v12.isDeleted());
    }
}
